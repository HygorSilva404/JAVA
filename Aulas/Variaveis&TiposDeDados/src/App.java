public class App {
    public static void main(String[] args) throws Exception {
        // tipo nome
        byte numeroPequeno = 124;
        short numeroShort = 32767;
        int numeroMaior = 2147483647;
        long numeroEnomer = 922337203685477000l;

        // variaveis do tipo ponto flutuante
        float peso = 87.9f;
        double pi = 3.13456756310986734566743303;

        // Variaveis do tipo caractere
        char letra = 'a';

        // variavel booleano 
        boolean estouComFome = true;

        System.out.println(numeroPequeno);
        System.out.println(numeroShort);
        System.out.println(numeroMaior);
        System.out.println(numeroEnomer);
        System.out.println(peso);
        System.out.println(pi);
        System.out.println(estouComFome);
        System.out.println(letra);

    }
}
